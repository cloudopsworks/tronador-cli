#!/usr/bin/env sh
set -eu

repo_root=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
work_dir=$(mktemp -d)
trap 'rm -rf "$work_dir"' EXIT INT TERM
mkdir -p "$work_dir/bin"

# A unique dist keeps the snapshot from replacing any developer release output.
awk -v dist="$work_dir/dist" '
  /^dist: dist-windows$/ { print "dist: " dist; next }
  { gsub(/\.\/dist-windows\//, dist "/"); print }
' "$repo_root/windows.goreleaser.yml" > "$work_dir/windows.goreleaser.yml"

# GoReleaser generates the package contents; the stub only replaces the
# Windows-only `choco pack` executable needed to zip those contents on Unix.
cat > "$work_dir/bin/choco" <<'SH'
#!/usr/bin/env sh
set -eu
[ "$#" -eq 4 ] && [ "$1" = pack ] && [ "$3" = --out ] || {
  echo 'Unexpected Chocolatey command (only local pack is allowed)' >&2
  exit 1
}
nuspec=$2
out=$4
[ -f "$nuspec" ] || exit 1
version=$(sed -n 's/.*<version>\(.*\)<\/version>.*/\1/p' "$nuspec")
[ -n "$version" ] || exit 1
package_dir=$(dirname "$nuspec")
package_name=$(basename "$nuspec" .nuspec)
(cd "$package_dir" && zip -q -r "$out/$package_name.$version.nupkg" .)
SH
chmod +x "$work_dir/bin/choco"

cd "$repo_root"
goreleaser check --config "$work_dir/windows.goreleaser.yml"
PATH="$work_dir/bin:$PATH" goreleaser release --snapshot --config "$work_dir/windows.goreleaser.yml" --skip=before,sign > "$work_dir/goreleaser.log" 2>&1 || {
  cat "$work_dir/goreleaser.log" >&2
  exit 1
}

dist="$work_dir/dist"
nuspec="$dist/tronador-cli.choco/tronador-cli.nuspec"
installer="$dist/tronador-cli.choco/tools/chocolateyinstall.ps1"
[ -f "$nuspec" ] && [ -f "$installer" ] || {
  echo 'GoReleaser did not generate native Chocolatey sources' >&2
  exit 1
}
grep -F '<id>tronador-cli</id>' "$nuspec" >/dev/null
grep -F 'This file was generated by GoReleaser' "$installer" >/dev/null
grep -F 'Install-ChocolateyZipPackage @packageArgs' "$installer" >/dev/null
grep -F 'windows_386.zip' "$installer" >/dev/null
grep -F 'windows_amd64.zip' "$installer" >/dev/null

package=$(find "$dist" -maxdepth 1 -name 'tronador-cli.*.nupkg' -type f -print)
[ -n "$package" ] && [ "$(printf '%s\n' "$package" | wc -l | tr -d ' ')" = 1 ] || {
  echo 'Expected exactly one native Chocolatey package' >&2
  exit 1
}
unzip -Z -1 "$package" | grep -F 'tools/chocolateyinstall.ps1' >/dev/null
unzip -Z -1 "$package" | grep -F 'tronador-cli.nuspec' >/dev/null

archive=$(find "$dist" -maxdepth 1 -name 'tronador-cli_*_windows_amd64.zip' -type f -print)
[ -n "$archive" ] || { echo 'Missing Windows amd64 archive' >&2; exit 1; }
unzip -Z -1 "$archive" | grep -x 'tronador.exe' >/dev/null
if unzip -Z -1 "$archive" | grep -x 'tronador-cli.exe' >/dev/null; then
  echo 'Windows archive contains the obsolete executable name' >&2
  exit 1
fi

printf 'Native GoReleaser Chocolatey snapshot fixture passed\n'
